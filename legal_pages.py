def canonical_redirect(host):
    """루트 도메인으로 들어온 '홈(/)' GET 요청만 www 대표 주소로 보낼 목적지를 돌려준다.

    - CANONICAL_HOST(예: www.example.co.kr) 가 설정되고 'www.' 로 시작할 때만 동작한다.
      미설정이면 항상 None(동작 변화 없음).
    - 요청 Host 가 정확히 루트(www 를 뺀 도메인)일 때만 이동한다. 그 외 호스트(Railway 주소 등)는
      건드리지 않는다. 목적지는 환경변수 값으로만 만들어 요청 값에 영향받지 않는다.
    - 호출 지점은 홈(/) 하나뿐이다. 결제 성공·실패·웹훅·API 경로는 이 함수를 쓰지 않는다.
    """
    canon = (os.environ.get("CANONICAL_HOST") or "").strip().lower()
    if not canon or not _HOST_RE.match(canon) or not canon.startswith("www."):
        return None
    apex = canon[4:]
    h = (host or "").split(":")[0].strip().lower()
    if h and h == apex:
        return "https://" + canon + "/"
    return None


